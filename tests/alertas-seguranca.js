'use strict';
const assert=require('node:assert/strict');
const {createSecurityAlerts}=require('../whatsapp');
(async()=>{
  let time=0,sends=[];
  const env={SECURITY_WHATSAPP_ENABLED:'1',SECURITY_WHATSAPP_TO:'5548999990001',SECURITY_WHATSAPP_TEMPLATE:'alerta_teste'};
  const options={env,now:()=>time,log:{log(){},error(){}},send:async(c,p)=>sends.push(p)};
  assert.throws(()=>createSecurityAlerts(null,options),/configure/);
  assert.throws(()=>createSecurityAlerts({}, {...options,env:{...env,SECURITY_WHATSAPP_TO:'554899990001'}}),/configure/);
  const off=createSecurityAlerts(null,{env:{}});off.record('rate_limit');assert.equal(await off.flush(),false);
  const alerts=createSecurityAlerts({},options);
  for(let i=0;i<19;i++)alerts.record('rate_limit');
  assert.equal(await alerts.flush(),false,'Poucos eventos não enviam alerta');
  alerts.record('login_limit');
  assert.equal(await alerts.flush(),true);
  assert.equal(sends.length,1);
  assert.equal(sends[0].type,'template');
  assert.equal(sends[0].to,env.SECURITY_WHATSAPP_TO);
  assert.match(sends[0].template.components[0].parameters[0].text,/Requisições limitadas: 19; login limitado: 1/);
  for(let i=0;i<10000;i++)alerts.record('rate_limit');
  assert.equal(await alerts.flush(),false,'Ataque não cria notificações em sequência');
  time+=300000;
  assert.equal(await alerts.flush(),true);
  assert.equal(sends.length,2);
  assert.match(sends[1].template.components[0].parameters[0].text,/10000/);
  let attempts=0;
  const failing=createSecurityAlerts({}, {...options,send:async()=>{attempts++;throw new Error('segredo que não pode ser logado');}});
  for(let i=0;i<20;i++)failing.record('overload');
  assert.equal(await failing.flush(),false);
  assert.equal(await failing.flush(),false);assert.equal(attempts,1);
  time+=300000;await failing.flush();assert.equal(attempts,2,'Falha aguarda intervalo e mantém contagens');
  let finish;
  const slow=createSecurityAlerts({}, {...options,send:()=>new Promise(r=>{finish=r;})});
  for(let i=0;i<20;i++)slow.record('payload_limit');
  const first=slow.flush();time+=300000;
  for(let i=0;i<20;i++)slow.record('payload_limit');
  assert.equal(await slow.flush(),false,'Um envio em andamento por vez');
  finish();await first;
  console.log('OK: configuração, agrupamento de 10.000 eventos, intervalo, falhas e envio único; nenhuma mensagem real enviada.');
})().catch(e=>{console.error(e);process.exitCode=1;});
